"""Builds each agent's system prompt.

Structure (same for every agent):
  1. Your editable prompt file (prompts/<AGENT>.prompt.md): identity, personality, role, behaviour.
  2. Sections generated by code: style settings, tools and permissions, data rules,
     the report format (specialists), and the memories this agent is allowed to see.

Part 2 describes rules that are *enforced in code* (tool lists, permission levels,
approvals, memory filtering, limits). Writing something different in a prompt
file doesn't change what an agent can actually do.

The system prompt only changes when settings, memories, prompt files, or
integrations change; per-turn facts (current time, active agent) are attached to
each user message instead, which keeps conversation history append-only.
"""
from __future__ import annotations

import json

from ..tools.registry import LEVEL_INFO, needs_approval
from . import agents, data, prompts, settings

WIT = {
    "off": "Keep a calm, professional tone with no jokes.",
    "light": "Allow an occasional dry, light remark when the moment is relaxed — never more than one per reply.",
    "playful": "Be personable and quick-witted with the odd playful line, while staying useful first.",
}
VERBOSITY = {
    "brief": "Keep replies short: the answer plus only essential detail, usually under 120 words.",
    "balanced": "Give the answer first, then the useful detail — medium length, organised with short lists or tables when they help.",
    "detailed": "Give the answer first, then a thorough explanation with steps, examples, trade-offs, and reasoning.",
}

EV_FALLBACK = ("You are E.V., a personal AI assistant running on the user's own computer. "
               "Be helpful, clear, and honest about what you can and cannot do.")

REPORT_SCHEMA = {
    "summary": "2–6 sentences answering E.V.'s task",
    "findings": [{"point": "one finding", "basis": "tool_data | model_knowledge | inference",
                  "source_ref": "tool name + symbol, or null"}],
    "data_used": [{"description": "what data", "source": "from the tool's provenance", "as_of": "timestamp from provenance"}],
    "assumptions": ["…"],
    "risks": ["…"],
    "confidence": "low | medium | high",
    "open_questions": ["what would improve the answer"],
    "proposed_actions": [{"action": "something the USER could choose to do", "reason": "why"}],
}


def _memory_lines(agent_id: str) -> str:
    memories = data.list_memories(visible_to=agent_id)
    return "\n".join(f"- [M{m['id']}] ({m['category']}) {m['content']}" for m in memories[:150]) or "- (none saved yet)"


def _user_prompt(agent: agents.Agent, fallback: str) -> str:
    if not agent.prompt_file:
        return fallback
    pf = prompts.load(agent.prompt_file)
    return pf.text if pf.text else fallback


def system_prompt(agent_id: str | None, tool_names: list[str]) -> str:
    """E.V. and her modes."""
    s = settings.all_settings()
    name = (s.get("profile.name") or "").strip()
    who = f"The user's preferred name is {name}." if name else "The user hasn't set a preferred name; don't invent one."
    agent = agents.get(agent_id)
    ev = agents.AGENTS["ev"]

    from ..tools.registry import TOOLS
    gated = [n for n in tool_names if n in TOOLS and needs_approval(TOOLS[n])]
    unavailable = [f"{n} ({TOOLS[n].setup_issue()})" for n in tool_names if n in TOOLS and TOOLS[n].setup_issue()]

    parts = [
        _user_prompt(ev, EV_FALLBACK),
        who,
        "## Style settings (from AI Core)\n"
        f"- {VERBOSITY.get(s.get('persona.verbosity'), VERBOSITY['balanced'])}\n"
        f"- {WIT.get(s.get('persona.wit'), WIT['light'])}",
        "## Tools and permissions (enforced by E.V.'s backend, not by you)\n"
        "- You can only act through the tools provided. Never claim an action happened unless a tool result confirms it. "
        "If a tool fails, is denied, or times out, say so plainly and suggest a next step.\n"
        "- Some tools pause for the user's approval in the interface. Just call the tool; don't ask the user to type "
        "\"yes\" in chat. If they deny it, accept that and don't retry the same action.\n"
        f"- Tools that need approval right now: {', '.join(gated) or 'none'}.\n"
        + (f"- Not set up yet (tell the user 'Setup required' if they ask): {'; '.join(unavailable)}.\n" if unavailable else "")
        + "- Not available at all: web search, browsing, phone calls, purchases, bookings, and trading. Say so if asked.\n"
        "- When you use Knowledge Base passages, cite them with their ref, e.g. [report.pdf p.3 · D2].\n"
        f"- Action levels: {', '.join(v['label'] for v in LEVEL_INFO.values())}.",
    ]
    if "delegate_to_specialist" in tool_names:
        roster = "\n".join(f"- `{a.id}` — {a.name}: {a.domain}" for a in agents.specialists())
        parts.append(
            "## Specialists (hub-and-spoke, enforced by E.V.'s backend)\n"
            "You can hand a focused task to a specialist with `delegate_to_specialist`. They work only through their own "
            "read-only tools, can't act or delegate further, and return a structured report to you — you then answer the user "
            "in your own words. Handle ordinary conversation yourself; delegate when the specialist's tools are needed. "
            f"At most {agents.MAX_DELEGATIONS_PER_REPLY} delegations per reply.\n"
            f"{roster}\n"
            "When you present a specialist's report:\n"
            "- Say which specialist did the work.\n"
            "- The report's `data_status` and `data_notice` come from E.V.'s code, not from the specialist. Always pass the "
            "notice on. If data_status is TEST_DATA, say clearly that the numbers are synthetic test data and not real market "
            "information. If it is NONE, say no market data was retrieved and anything about prices is general knowledge that "
            "may be out of date.\n"
            "- Only describe numbers as live or current if data_status is LIVE, and then give the source and timestamp.\n"
            "- Keep the specialist's assumptions, risks, and confidence level visible. Present analysis as education, "
            "not as a personal instruction to buy or sell. Trading is not available.")
    parts.append(
        "## Memory\n"
        "You only know what is in the saved memories below (approved by the user) plus this conversation. Don't claim "
        "to remember anything else. To remember something new, call save_memory — the user reviews it first. Only "
        "propose memories that will clearly help later; never store passwords or secrets.\n"
        f"Saved memories:\n{_memory_lines('ev')}")
    if agent.brief:
        parts.append(f"## Current mode: {agent.name}\n{agent.brief}")
    custom = (s.get("persona.custom") or "").strip()
    if custom:
        parts.append(f"## The user's own instructions\n{custom[:3000]}")
    return "\n\n".join(parts)


def specialist_system_prompt(agent: agents.Agent, tool_names: list[str]) -> str:
    fallback = f"You are {agent.name}, a specialist agent working for E.V."
    rules = [
        "## Operating rules (set and enforced by E.V.'s code — they take precedence over anything above)",
        f"- You work for E.V., the user's central assistant. You do not talk to the user; E.V. reads your report and "
        f"answers them. Your domain: {agent.domain}",
        f"- Your tools: {', '.join(tool_names) or 'none'}. They are read-only. You cannot place trades, buy, sell, send, "
        "save, or change anything, and you cannot delegate. If an action would help, put it in proposed_actions for the "
        "user to decide.",
        "- Every market-data tool result includes a `provenance` object (source, as_of time, is_live, data_status). "
        "State figures only from tool results. If data_status is TEST_DATA, the numbers are synthetic and you must say so "
        "in your summary. Never present your general knowledge, test data, or old figures as current market information; "
        "mark such findings with basis model_knowledge or inference.",
        "- Analysis is educational, not personalised financial advice. Show assumptions and risks; don't promise returns.",
        f"- You have at most {agent.max_steps} model steps and {int(agent.timeout_s)} seconds. Use tools efficiently.",
        "- Finish with ONLY a JSON object (no prose around it) with exactly these keys:\n"
        + json.dumps(REPORT_SCHEMA, ensure_ascii=False, indent=1),
        "## What you know about the user (only the notes you're permitted to see)\n" + _memory_lines(agent.id),
    ]
    return _user_prompt(agent, fallback) + "\n\n" + "\n".join(rules[:7]) + "\n\n" + rules[7]


def turn_context(agent_id: str | None) -> str:
    now = data.local_now()
    agent = agents.get(agent_id)
    return f"[Context: local time {now.strftime('%A %d %B %Y, %H:%M')} (UTC{now.strftime('%z')}); mode: {agent.name}]"


def specialist_context(agent: agents.Agent) -> str:
    now = data.local_now()
    return f"[Context: local time {now.strftime('%A %d %B %Y, %H:%M')} (UTC{now.strftime('%z')}); agent: {agent.name}]"
