"""Market data for F.R.I.D.A.Y. — deliberately separate from AI connections.

An AI provider key (Groq, Claude, OpenAI…) does NOT give live stock prices or
financial news. Market data comes from its own source, chosen in
Settings → Market data (setting `market_data.source`).

Sources available in this version:
  * "test" — a built-in generator of SYNTHETIC numbers so the delegation flow can
             be exercised end to end. Every value it returns is labelled TEST_DATA,
             company names are fake, and headlines are marked [TEST DATA].
  * "none" — market tools report "Setup required".

No live source is connected yet. To add one (e.g. Finnhub, Alpha Vantage, Massive,
Tiingo), subclass MarketSource, keep its API key in .env via config.SECRET_NAMES,
set is_live = True, return real provenance (source name + the provider's own
timestamp), and register it in SOURCES. See the README for options.

Every result carries a provenance object built here, in code, so the label can't
be lost or rewritten by a model:
    {source_id, source, data_status: TEST_DATA | LIVE | DELAYED | END_OF_DAY,
     is_live, as_of, retrieved_at, note}
"""
from __future__ import annotations

import hashlib
import random
from datetime import date, datetime, timedelta, timezone
from typing import Any

from ..services import settings

RANGES = {"1m": 21, "3m": 63, "6m": 126, "1y": 252, "5y": 1260}
MAX_POINTS = 60


class MarketSource:
    id = ""
    label = ""
    is_live = False
    data_status = "TEST_DATA"

    def setup_issue(self) -> str | None:
        return None

    def provenance(self, as_of: str | None = None) -> dict[str, Any]:
        now = datetime.now(timezone.utc).replace(microsecond=0).isoformat()
        return {"source_id": self.id, "source": self.label, "data_status": self.data_status, "is_live": self.is_live,
                "as_of": as_of or now, "retrieved_at": now, "note": self.note()}

    def note(self) -> str:
        return ""

    async def quote(self, symbol: str) -> dict[str, Any]: raise NotImplementedError
    async def overview(self, symbol: str) -> dict[str, Any]: raise NotImplementedError
    async def history(self, symbol: str, rng: str) -> dict[str, Any]: raise NotImplementedError
    async def news(self, symbol: str, limit: int) -> dict[str, Any]: raise NotImplementedError


class TestSource(MarketSource):
    """Deterministic synthetic data. Same symbol + same day → same numbers."""
    id = "test"
    label = "E.V. built-in TEST-DATA generator (synthetic, not real market data)"
    is_live = False
    data_status = "TEST_DATA"

    def note(self) -> str:
        return "SYNTHETIC TEST DATA. These numbers were generated by E.V. for testing and do not describe any real security."

    @staticmethod
    def _rng(symbol: str, salt: str = "") -> random.Random:
        seed = int(hashlib.sha256(f"{symbol}|{salt}".encode()).hexdigest()[:12], 16)
        return random.Random(seed)

    def _series(self, symbol: str, days: int) -> list[tuple[str, float]]:
        r = self._rng(symbol)
        price = round(20 + r.random() * 380, 2)
        drift = (r.random() - 0.45) * 0.002
        vol = 0.008 + r.random() * 0.02
        # Walk forward over a fixed 1,300 trading-day window ending today, so ranges agree.
        dates: list[date] = []
        d = date.today()
        while len(dates) < 1300:
            if d.weekday() < 5:
                dates.append(d)
            d -= timedelta(days=1)
        dates.reverse()
        out = []
        for dt in dates:
            price = max(1.0, price * (1 + drift + r.gauss(0, vol)))
            out.append((dt.isoformat(), round(price, 2)))
        return out[-days:]

    async def quote(self, symbol: str) -> dict[str, Any]:
        s = self._series(symbol, 2)
        prev, last = s[0][1], s[1][1]
        r = self._rng(symbol, s[1][0])
        return {"label": "TEST DATA", "currency": "USD", "price": last, "previous_close": prev,
                "change": round(last - prev, 2), "change_percent": round((last - prev) / prev * 100, 2),
                "open": round(prev * (1 + r.uniform(-0.01, 0.01)), 2),
                "day_high": round(max(prev, last) * (1 + r.uniform(0, 0.015)), 2),
                "day_low": round(min(prev, last) * (1 - r.uniform(0, 0.015)), 2), "date": s[1][0]}

    async def overview(self, symbol: str) -> dict[str, Any]:
        r = self._rng(symbol, "profile")
        year = self._series(symbol, 252)
        closes = [c for _, c in year]
        eps = round(r.uniform(-2, 12), 2)
        return {"label": "TEST DATA", "name": f"TEST DATA — {symbol} Sample Company (not a real company)",
                "sector": "Synthetic", "industry": "Synthetic test data", "currency": "USD",
                "market_cap_usd": int(closes[-1] * r.uniform(5e7, 5e9)),
                "pe_ratio": round(closes[-1] / eps, 1) if eps > 0 else None, "eps_ttm": eps,
                "dividend_yield_percent": round(r.uniform(0, 3.5), 2) if r.random() > 0.4 else 0.0,
                "week52_high": max(closes), "week52_low": min(closes),
                "description": "Synthetic profile generated by E.V. for testing. It does not describe any real company."}

    async def history(self, symbol: str, rng: str) -> dict[str, Any]:
        s = self._series(symbol, RANGES[rng])
        step = max(1, len(s) // MAX_POINTS)
        points = s[::step]
        if points[-1] != s[-1]:
            points.append(s[-1])
        closes = [c for _, c in s]
        return {"label": "TEST DATA", "range": rng, "interval": f"every {step} trading day(s)",
                "start": {"date": s[0][0], "close": s[0][1]}, "end": {"date": s[-1][0], "close": s[-1][1]},
                "change_percent": round((s[-1][1] - s[0][1]) / s[0][1] * 100, 2),
                "high": max(closes), "low": min(closes),
                "closes": [{"date": d, "close": c} for d, c in points]}

    async def news(self, symbol: str, limit: int) -> dict[str, Any]:
        today = datetime.now(timezone.utc).replace(microsecond=0)
        return {"label": "TEST DATA", "articles": [
            {"headline": f"[TEST DATA] Sample headline {i + 1} about {symbol} — not a real article",
             "summary": "Placeholder text generated for testing. No real event is described.",
             "source": "Synthetic", "published_at": (today - timedelta(hours=6 * (i + 1))).isoformat(), "url": None}
            for i in range(limit)]}


SOURCES: dict[str, MarketSource] = {"test": TestSource()}

# Live sources E.V. could add, with what each needs (shown in Settings; nothing here is connected).
OPTIONS = [
    {"id": "finnhub", "name": "Finnhub", "credential": "FINNHUB_API_KEY (free key from finnhub.io)", "status": "not_built"},
    {"id": "alpha_vantage", "name": "Alpha Vantage", "credential": "ALPHA_VANTAGE_API_KEY", "status": "not_built"},
    {"id": "massive", "name": "Massive (formerly Polygon.io)", "credential": "MASSIVE_API_KEY", "status": "not_built"},
    {"id": "tiingo", "name": "Tiingo", "credential": "TIINGO_API_TOKEN", "status": "not_built"},
]


def active() -> MarketSource | None:
    return SOURCES.get(settings.get("market_data.source") or "none")


def setup_issue() -> str | None:
    src = active()
    if src is None:
        return "No market-data source is selected (Settings → Market data)."
    return src.setup_issue()


def status() -> dict[str, Any]:
    src = active()
    return {"source": settings.get("market_data.source"), "label": src.label if src else "Off",
            "is_live": bool(src and src.is_live), "data_status": src.data_status if src else "NONE",
            "setup_issue": setup_issue(), "available": [{"id": k, "label": v.label, "is_live": v.is_live} for k, v in SOURCES.items()],
            "options": OPTIONS}
